using FluentAssertions;

namespace Markdown.Tests;

[TestFixture]
public class MarkdownConverterTests
{
    [TestCaseSource(nameof(MarkdownCases))]
    public void ToHtml_MarkdownSpecText_ReturnsExpectedHtml(string markdown, string expected)
    {
        var actual = MarkdownConverter.ToHtml(markdown);

        actual.Should().Be(expected);
    }

    private static IEnumerable<TestCaseData> MarkdownCases()
    {
        yield return new TestCaseData(
            """
            Текст, _окруженный с двух сторон_ одинарными символами подчерка,
            должен помещаться в HTML-тег <em>
            """,
            "<p>Текст, <em>окруженный с двух сторон</em> одинарными символами подчерка, должен помещаться в HTML-тег <em></p>");

        yield return new TestCaseData(
            "__Выделенный двумя символами текст__ должен становиться полужирным с помощью тега <strong>.",
            "<p><strong>Выделенный двумя символами текст</strong> должен становиться полужирным с помощью тега <strong>.</p>");

        yield return new TestCaseData(
            """
            Любой символ можно экранировать, чтобы он не считался частью разметки.
            \_Вот это\_, не должно выделиться тегом <em>.
            """,
            "<p>Любой символ можно экранировать, чтобы он не считался частью разметки. _Вот это_, не должно выделиться тегом <em>.</p>");

        yield return new TestCaseData(
            @"Символ экранирования тоже можно экранировать: \\_вот это будет выделено тегом_ <em>",
            @"<p>Символ экранирования тоже можно экранировать: \<em>вот это будет выделено тегом</em> <em></p>");

        yield return new TestCaseData(
            "Внутри __двойного выделения _одинарное_ тоже__ работает.",
            "<p>Внутри <strong>двойного выделения <em>одинарное</em> тоже</strong> работает.</p>");

        yield return new TestCaseData(
            "Но не наоборот — внутри _одинарного __двойное__ не_ работает.",
            "<p>Но не наоборот — внутри <em>одинарного __двойное__ не</em> работает.</p>");

        yield return new TestCaseData(
            "Подчерки внутри текста c цифрами_12_3 не считаются выделением и должны оставаться символами подчерка.",
            "<p>Подчерки внутри текста c цифрами_12_3 не считаются выделением и должны оставаться символами подчерка.</p>");

        yield return new TestCaseData(
            "Однако выделять часть слова они могут: и в _нач_але, и в сер_еди_не, и в кон_це._",
            "<p>Однако выделять часть слова они могут: и в <em>нач</em>але, и в сер<em>еди</em>не, и в кон<em>це.</em></p>");

        yield return new TestCaseData(
            "В то же время выделение в ра_зных сл_овах не работает.",
            "<p>В то же время выделение в ра_зных сл_овах не работает.</p>");

        yield return new TestCaseData(
            "__Непарные_ символы в рамках одного абзаца не считаются выделением.",
            "<p>__Непарные_ символы в рамках одного абзаца не считаются выделением.</p>");

        yield return new TestCaseData(
            """
            За подчерками, начинающими выделение, должен следовать непробельный символ. Иначе эти_ подчерки_ не считаются выделением 
            и остаются просто символами подчерка.
            """,
            "<p>За подчерками, начинающими выделение, должен следовать непробельный символ. Иначе эти_ подчерки_ не считаются выделением и остаются просто символами подчерка.</p>");

        yield return new TestCaseData(
            """
            Подчерки, заканчивающие выделение, должны следовать за непробельным символом. Иначе эти _подчерки _не считаются_ окончанием выделения
            и остаются просто символами подчерка.
            """,
            "<p>Подчерки, заканчивающие выделение, должны следовать за непробельным символом. Иначе эти _подчерки <em>не считаются</em> окончанием выделения и остаются просто символами подчерка.</p>");


        yield return new TestCaseData(
            "В случае __пересечения _двойных__ и одинарных_ подчерков ни один из них не считается выделением.",
            "<p>В случае __пересечения _двойных__ и одинарных_ подчерков ни один из них не считается выделением.</p>");

        yield return new TestCaseData(
            "Если внутри подчерков пустая строка ____, то они остаются символами подчерка.",
            "<p>Если внутри подчерков пустая строка ____, то они остаются символами подчерка.</p>");

        yield return new TestCaseData(
            "# Заголовок __с _разными_ символами__",
            "<h1>Заголовок <strong>с <em>разными</em> символами</strong></h1>");
    }
}