using AwesomeAssertions;
using NUnit.Framework;

namespace Markdown.Tests;

[TestFixture]
public class EmphasisTests
{
    private static readonly TestCaseData[] Cases =
    {
        RenderCase.Create(
            "Пара одиночных подчерков вокруг одного слова оборачивает это слово в тег em",
            "_курсив_",
            "<p><em>курсив</em></p>"),

        RenderCase.Create(
            "В одиночные подчерки можно заключать несколько слов",
            "_несколько слов_",
            "<p><em>несколько слов</em></p>"),

        RenderCase.Create(
            "Несколько разных курсивных слов в одном абзаце",
            "_первый_ и _второй_",
            "<p><em>первый</em> и <em>второй</em></p>"),

        RenderCase.Create(
            "Курсивом можно выделить часть слова в начале",
            "_нач_але",
            "<p><em>нач</em>але</p>"),

        RenderCase.Create(
            "Курсивом можно выделить часть слова в середине",
            "сер_еди_не",
            "<p>сер<em>еди</em>не</p>"),

        RenderCase.Create(
            "Курсивом можно выделить часть слова и в конце",
            "кон_це._",
            "<p>кон<em>це.</em></p>"),

        RenderCase.Create(
            "Подчерки внутри разных слов не создают курсивную пару",
            "ра_зных сл_овах",
            "<p>ра_зных сл_овах</p>"),

        RenderCase.Create(
            "Просто один символ подчерка остается в виде текста",
            "_",
            "<p>_</p>"),

        RenderCase.Create(
            "Непарный подчерк остается в виде текста",
            "непарный _текст",
            "<p>непарный _текст</p>"),

        RenderCase.Create(
            "Если внетри пары подчерков ничего нет то они остаются текстом",
            "____",
            "<p>____</p>"),

        RenderCase.Create(
            "Открывающий подчерк после которого следует пробельный символ не создает курсив",
            "_ текст_",
            "<p>_ текст_</p>"),

        RenderCase.Create(
            "Закрывающий подчерк перед которым идет пробельный символ не закрывает курсивную пару",
            "_текст _",
            "<p>_текст _</p>"),

        RenderCase.Create(
            "Подчерк внутри цифр не создает курсив",
            "цифрами_12_3",
            "<p>цифрами_12_3</p>"),

        RenderCase.Create(
            "Подчерк после которого идет цифровой символ не влияет на курсив",
            "_1a_",
            "<p>_1a_</p>"),

        RenderCase.Create(
            "Подчерк перед которым идет цифровой символ не влияет на курсив",
            "_a1_",
            "<p>_a1_</p>"),
    };

    [TestCaseSource(nameof(Cases))]
    public void Render_ReturnsExpectedHtml(string input, string expected)
    {
        Md.Render(input).Should().Be(expected);
    }
}
